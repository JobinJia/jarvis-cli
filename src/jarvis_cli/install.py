# Sentinel comments wrap the block we own inside ~/.codex/config.toml so
# successive installs can find and replace the block without disturbing
# anything the user has hand-edited around it.
_CODEX_BLOCK_START = "# === jarvis-cli:start ==="
_CODEX_BLOCK_END = "# === jarvis-cli:end ==="
_CODEX_BLOCK_RE = re.compile(
    re.escape(_CODEX_BLOCK_START) + r".*?" + re.escape(_CODEX_BLOCK_END) + r"\n?",
    re.DOTALL,
)


def _is_our_hook(hook: dict) -> bool:
    """Match any entry whose command basename is jarvis-cli-hook (legacy bare
    name or absolute path from a previous install in a different venv)."""
    return Path(hook.get("command", "")).name == "jarvis-cli-hook"


_OUR_HOOK_TYPES = (
    "Notification",
    "UserPromptSubmit",
    "PostToolUse",
    "PostToolUseFailure",
    "SessionStart",
    "Stop",
)


def merge_claude_settings(existing: dict, hook_command: str) -> dict:
    """Install our hook entries into Notification, UserPromptSubmit, and
    PostToolUse, replacing any prior jarvis-cli-hook entries in those buckets.
    """
    out = copy.deepcopy(existing)
    hooks = out.setdefault("hooks", {})
    for hook_type in _OUR_HOOK_TYPES:
        entries = hooks.setdefault(hook_type, [])
        pruned: list[dict] = []
        for matcher in entries:
            kept = [h for h in matcher.get("hooks", []) if not _is_our_hook(h)]
            if kept:
                pruned.append({**matcher, "hooks": kept})
        pruned.append(
            {"matcher": "", "hooks": [{"type": "command", "command": hook_command}]}
        )
        out["hooks"][hook_type] = pruned
    return out


def remove_from_claude_settings(existing: dict, hook_command: str) -> dict:
    """Strip our jarvis-cli-hook entries from every hook bucket we install into.

    `hook_command` is accepted for signature compat; matching is by basename.
    """
    out = copy.deepcopy(existing)
    hooks = out.get("hooks", {})
    for hook_type in _OUR_HOOK_TYPES:
        entries = hooks.get(hook_type, [])
        filtered = []
        for matcher in entries:
            kept = [h for h in matcher.get("hooks", []) if not _is_our_hook(h)]
            if kept:
                filtered.append({**matcher, "hooks": kept})
        if filtered:
            hooks[hook_type] = filtered
        else:
            hooks.pop(hook_type, None)
    return out


def _render_codex_block(hook_command: str) -> str:
    """Render the TOML snippet we own inside ~/.codex/config.toml.

    Includes `notify` (Codex's async per-turn webhook) and lifecycle
    hooks for the events that map cleanly onto our daemon's notification
    model. PreToolUse fires on every tool call; we let the daemon's
    dedup window handle the noise so each `[[hooks.PreToolUse]]` entry
    here is unconditional (matcher = ".*").
    """
    return (
        f"{_CODEX_BLOCK_START}\n"
        "# Auto-generated by `jarvis-cli install`. Anything between these\n"
        "# markers is replaced on the next install; remove via `jarvis-cli uninstall`.\n"
        "\n"
        f'notify = ["{hook_command}"]\n'
        "\n"
        "[[hooks.PreToolUse]]\n"
        'matcher = ".*"\n'
        "[[hooks.PreToolUse.hooks]]\n"
        'type = "command"\n'
        f'command = "{hook_command}"\n'
        "timeout = 5\n"
        "\n"
        "[[hooks.PermissionRequest]]\n"
        'matcher = ".*"\n'
        "[[hooks.PermissionRequest.hooks]]\n"
        'type = "command"\n'
        f'command = "{hook_command}"\n'
        "timeout = 5\n"
        "\n"
        "[[hooks.UserPromptSubmit]]\n"
        "[[hooks.UserPromptSubmit.hooks]]\n"
        'type = "command"\n'
        f'command = "{hook_command}"\n'
        "timeout = 5\n"
        "\n"
        "[[hooks.PostToolUse]]\n"
        "[[hooks.PostToolUse.hooks]]\n"
        'type = "command"\n'
        f'command = "{hook_command}"\n'
        "timeout = 5\n"
        "\n"
        "[[hooks.PostToolUseFailure]]\n"
        'matcher = ".*"\n'
        "[[hooks.PostToolUseFailure.hooks]]\n"
        'type = "command"\n'
        f'command = "{hook_command}"\n'
        "timeout = 5\n"
        "\n"
        "[[hooks.Stop]]\n"
        "[[hooks.Stop.hooks]]\n"
        'type = "command"\n'
        f'command = "{hook_command}"\n'
        "timeout = 5\n"
        "\n"
        "[[hooks.SessionStart]]\n"
        "[[hooks.SessionStart.hooks]]\n"
        'type = "command"\n'
        f'command = "{hook_command}"\n'
        "timeout = 5\n"
        f"{_CODEX_BLOCK_END}\n"
    )


def merge_codex_config(existing: str, hook_command: str) -> str:
    """Inject (or replace) our managed hook block in a Codex config.toml.

    TOML constrains where bare top-level keys (like `notify`) may appear:
    they must precede any `[section]` header. We therefore insert our
    block *before* the first section header in the user's file, after
    any existing top-level keys. If the block is already present we
    replace it in place. If there are no section headers we append at
    the end.
    """
    block = _render_codex_block(hook_command)
    if _CODEX_BLOCK_RE.search(existing):
        return _CODEX_BLOCK_RE.sub(block, existing)

    lines = existing.splitlines(keepends=True)
    insert_at = None
    for i, line in enumerate(lines):
        stripped = line.lstrip()
        if stripped.startswith("["):
            insert_at = i
            break
    if insert_at is None:
        # No [section] headers — append (preserve trailing newline)
        sep = "\n" if existing and not existing.endswith("\n") else ""
        return existing + sep + "\n" + block

    # Drop trailing blank lines from the head so we don't accumulate them.
    head = "".join(lines[:insert_at]).rstrip() + "\n\n"
    tail = "".join(lines[insert_at:])
    return head + block + "\n" + tail


def remove_from_codex_config(existing: str) -> str:
    """Strip our managed block from a Codex config.toml; no-op if absent."""
    cleaned = _CODEX_BLOCK_RE.sub("", existing)
    # Collapse the double blank line we may have left behind.
    return re.sub(r"\n{3,}", "\n\n", cleaned)


def render_plist(label: str, program: str, log_dir: str, env: dict[str, str]) -> str:
    """Render a launchd plist for the daemon."""
    env_xml = "\n".join(
        f"        <key>{k}</key>\n        <string>{v}</string>"
        for k, v in env.items()
    )
    return textwrap.dedent(
        f"""\
        <?xml version="1.0" encoding="UTF-8"?>
        <!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
        <plist version="1.0">
        <dict>
            <key>Label</key>
            <string>{label}</string>
            <key>ProgramArguments</key>
            <array>
                <string>{program}</string>
            </array>
            <key>RunAtLoad</key>
            <true/>
            <key>KeepAlive</key>
            <true/>
            <key>StandardOutPath</key>
            <string>{log_dir}/daemon.stdout.log</string>
            <key>StandardErrorPath</key>
            <string>{log_dir}/daemon.stderr.log</string>
            <key>EnvironmentVariables</key>
            <dict>
{env_xml}
            </dict>
        </dict>
        </plist>
        """
    )


