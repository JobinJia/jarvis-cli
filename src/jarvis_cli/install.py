def _extract_preservable(cfg_path: Path) -> dict:
    """Pull forward a handful of tuned values from an existing config so a
    re-run of the wizard doesn't blow them away. Best-effort — any parse
    failure leaves the dict empty and the wizard falls back to defaults.
    """
    if not cfg_path.exists():
        return {}
    try:
        cfg = load_config(cfg_path)
    except Exception:  # noqa: BLE001 — wizard must never abort on parse drift
        return {}
    return {
        "humor_level": cfg.behavior.humor_level,
        "voice_language": cfg.behavior.voice_language,
        "city": cfg.behavior.session_briefing.city,
        "ref_text_en": cfg.tts.cosyvoice.ref_text_en,
        "elevenlabs_voice_id": cfg.tts.elevenlabs.voice_id,
        "cosyvoice_n_timesteps": cfg.tts.cosyvoice.n_timesteps,
    }


def cmd_install(args: argparse.Namespace) -> int:
    # 1. Make jarvis-cli dir tree
    base = Path(JARVIS_DIR)
    (base / "voices").mkdir(parents=True, exist_ok=True)
    (base / "models").mkdir(parents=True, exist_ok=True)
    (base / "logs").mkdir(parents=True, exist_ok=True)

    # 2. Wizard / config
    cfg_path = Path(DEFAULT_CONFIG_PATH)
    interactive = _is_interactive() and not getattr(args, "non_interactive", False)
    env = scan_environment(base)
    _print_env_summary(env)

    fresh = not cfg_path.exists()
    reconfigure = getattr(args, "reconfigure", False)
    run_the_wizard = fresh or reconfigure

    if run_the_wizard:
        existing = _extract_preservable(cfg_path) if cfg_path.exists() else None
        choices = run_wizard(env, existing=existing, interactive=interactive)
        rendered = _render_configured_toml(
            choices,
            preserve=existing or {},
        )
        if cfg_path.exists():
            backup = cfg_path.with_suffix(cfg_path.suffix + ".bak")
            shutil.copy2(cfg_path, backup)
            print(f"  backed up old config → {backup}")
        cfg_path.write_text(rendered, encoding="utf-8")
        print(f"  wrote {cfg_path} (humor={choices.humor_level}, "
              f"profile={choices.profile})")
    else:
        print(f"  (kept existing {cfg_path}; pass --reconfigure to re-run wizard)")

    # 3. Patch ~/.claude/settings.json
    settings_path = Path(CLAUDE_SETTINGS_PATH)
    settings_path.parent.mkdir(parents=True, exist_ok=True)
    existing = {}
    if settings_path.exists():
        try:
            existing = json.loads(settings_path.read_text())
        except json.JSONDecodeError:
            print(f"!! could not parse {settings_path}, refusing to overwrite", file=sys.stderr)
            return 2
    hook_command = shutil.which("jarvis-cli-hook")
    if not hook_command:
        print("!! jarvis-cli-hook not on PATH — did you run `uv sync`?", file=sys.stderr)
        return 4
    merged = merge_claude_settings(existing, hook_command=hook_command)
    settings_path.write_text(json.dumps(merged, indent=2, ensure_ascii=False) + "\n")
    print(f"  patched {settings_path} (hook → {hook_command})")

    # 3b. Patch ~/.codex/config.toml if Codex CLI is on this machine.
    # We detect by file existence rather than `which codex` so a user who
    # has Codex's config dir but a non-PATH binary still gets wired up.
    codex_path = Path(CODEX_CONFIG_PATH)
    if codex_path.exists() or codex_path.parent.exists():
        codex_path.parent.mkdir(parents=True, exist_ok=True)
        existing_codex = codex_path.read_text(encoding="utf-8") if codex_path.exists() else ""
        merged_codex = merge_codex_config(existing_codex, hook_command=hook_command)
        codex_path.write_text(merged_codex, encoding="utf-8")
        print(f"  patched {codex_path} (Codex CLI detected)")
    else:
        print("  (no ~/.codex/ — skipping Codex hook setup)")

    # 4. Write plist
    program = shutil.which("jarvis-cli-daemon")
    if not program:
        print("!! jarvis-cli-daemon not on PATH — did you run `uv sync`?", file=sys.stderr)
        return 3
    plist_path = Path(PLIST_PATH)
    plist_path.parent.mkdir(parents=True, exist_ok=True)
    # Harvest API keys from the operator's current env so launchd can see them
    env = {"PATH": "/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin"}
    harvest_keys = [
        "DEEPSEEK_API_KEY",
        "ANTHROPIC_API_KEY",
        "OPENAI_API_KEY",
        "ELEVENLABS_API_KEY",
    ]
    for k in harvest_keys:
        v = os.environ.get(k)
        if v:
            env[k] = v
            print(f"  baked {k} into plist")
    # XTTS imports coqui-tts which blocks on a TTY prompt for the CPML
    # license unless COQUI_TOS_AGREED is set. The daemon has no TTY, so
    # without this it would hang on first XTTS synth. CosyVoice doesn't
    # need it but the env var is harmless when unused.
    env["COQUI_TOS_AGREED"] = "1"
    plist_path.write_text(render_plist(PLIST_LABEL, program, str(base / "logs"), env))
    print(f"  wrote {plist_path}")

    # 5. Load plist
    subprocess.run(["launchctl", "unload", str(plist_path)], check=False)
    rc = subprocess.run(["launchctl", "load", str(plist_path)], check=False).returncode
    if rc != 0:
        print(f"!! launchctl load returned {rc}", file=sys.stderr)
        return rc

    print(
        "\nDone. Next steps:\n"
        f"  1. Place reference audio at {base / 'voices/jarvis_zh.wav'} and "
        f"{base / 'voices/jarvis_en.wav'}\n"
        f"  2. If you didn't have DEEPSEEK_API_KEY in your env when you ran install,\n"
        f"     set it now and re-run `jarvis-cli install` (this re-bakes the plist).\n"
        f"  3. Restart Claude Code\n"
        f"  4. Run: jarvis-cli test\n"
    )
    return 0


def cmd_uninstall(args: argparse.Namespace) -> int:
    plist_path = Path(PLIST_PATH)
    if plist_path.exists():
        subprocess.run(["launchctl", "unload", str(plist_path)], check=False)
        plist_path.unlink()
        print(f"  removed {plist_path}")

    settings_path = Path(CLAUDE_SETTINGS_PATH)
    if settings_path.exists():
        try:
            existing = json.loads(settings_path.read_text())
            pruned = remove_from_claude_settings(existing, hook_command="jarvis-cli-hook")
            settings_path.write_text(json.dumps(pruned, indent=2, ensure_ascii=False) + "\n")
            print(f"  cleaned {settings_path}")
        except json.JSONDecodeError:
            pass

    codex_path = Path(CODEX_CONFIG_PATH)
    if codex_path.exists():
        cleaned = remove_from_codex_config(codex_path.read_text(encoding="utf-8"))
        codex_path.write_text(cleaned, encoding="utf-8")
        print(f"  cleaned {codex_path}")

    if args.purge:
        base = Path(JARVIS_DIR)
        if base.exists():
            shutil.rmtree(base)
            print(f"  purged {base}")
    else:
        print(f"  (kept {JARVIS_DIR}; pass --purge to remove)")
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    try:
        r = httpx.get("http://127.0.0.1:9527/health", timeout=1.0)
        print(json.dumps(r.json(), indent=2, ensure_ascii=False))
        return 0
    except httpx.HTTPError as exc:
        print(f"daemon unreachable: {exc}", file=sys.stderr)
        return 1


def cmd_test(args: argparse.Namespace) -> int:
    import socket as _socket

    from .config import load_config

    cfg = load_config(DEFAULT_CONFIG_PATH)
    payload = {
        "notification_type": args.event,
        "tool_name": args.tool,
        "tool_input": {},
        "cwd": os.getcwd(),
        "session_id": "test",
    }
    s = _socket.socket(_socket.AF_UNIX, _socket.SOCK_STREAM)
    try:
        s.connect(cfg.paths.socket)
        s.sendall((json.dumps(payload) + "\n").encode())
        print(f"sent {args.event} ({args.tool}) to {cfg.paths.socket}")
        return 0
    except OSError as exc:
        print(f"failed: {exc}", file=sys.stderr)
        return 1
    finally:
        s.close()


def cmd_say(args: argparse.Namespace) -> int:
    """Manual one-shot trigger for cases CC doesn't cover (e.g. an assistant
    that wants to alert the user before showing an AskUserQuestion UI).

    Sends a synthetic `idle_prompt` event; `--reason` gets stuffed into
    `tool_name` so the dedup hash is unique per call (no 10s collision) and
    so the LLM has a hint about why it's speaking.
    """
    import socket as _socket
    import uuid

    from .config import load_config

    cfg = load_config(DEFAULT_CONFIG_PATH)
    reason = args.reason or f"manual-{uuid.uuid4().hex[:8]}"
    payload: dict = {
        "notification_type": "idle_prompt",
        "tool_name": reason,
        "tool_input": {},
        "cwd": os.getcwd(),
        "session_id": "manual",
    }
    if args.text:
        payload["text"] = args.text
        payload["lang"] = args.lang
    if args.voice:
        payload["voice_id"] = args.voice
    s = _socket.socket(_socket.AF_UNIX, _socket.SOCK_STREAM)
    try:
        s.connect(cfg.paths.socket)
        s.sendall((json.dumps(payload) + "\n").encode())
        if args.text:
            print(f"queued say (text={args.text!r}, lang={args.lang})")
        else:
            print(f"queued say (reason={reason!r}, LLM will phrase it)")
        return 0
    except OSError as exc:
        print(f"failed: {exc}", file=sys.stderr)
        return 1
    finally:
        s.close()


def main() -> int:
    parser = argparse.ArgumentParser(prog="jarvis-cli")
    sub = parser.add_subparsers(dest="cmd", required=True)
    p_install = sub.add_parser("install")
    p_install.add_argument(
        "--reconfigure", action="store_true",
        help="re-run the setup wizard even when config.toml already exists",
    )
    p_install.add_argument(
        "--non-interactive", action="store_true",
        help="skip all prompts; take defaults (current values when present)",
    )
    p_install.set_defaults(func=cmd_install)
    p_un = sub.add_parser("uninstall")
    p_un.add_argument("--purge", action="store_true", help="also remove ~/.jarvis-cli/")
    p_un.set_defaults(func=cmd_uninstall)
    sub.add_parser("status").set_defaults(func=cmd_status)
    p_test = sub.add_parser("test")
    p_test.add_argument("--event", default="permission_prompt")
    p_test.add_argument("--tool", default="Bash")
    p_test.set_defaults(func=cmd_test)
    p_say = sub.add_parser(
        "say",
        help="manually trigger Jarvis to speak (bypasses dedup; for events CC's "
        "Notification hook doesn't cover, eg AskUserQuestion)",
    )
    p_say.add_argument(
        "--reason",
        default=None,
        help="short label that flows into the LLM prompt as `tool_name`",
    )
    p_say.add_argument(
        "--text",
        default=None,
        help="speak this exact text; skips the LLM entirely",
    )
    p_say.add_argument(
        "--lang",
        default="en",
        choices=["en", "zh"],
        help="language of --text (default: en); ignored without --text",
    )
    p_say.add_argument(
        "--voice",
        default=None,
        help="per-call TTS voice override (eg an ElevenLabs voice_id or a "
        "macOS `say` voice name like Karen); defaults to config",
    )
    p_say.set_defaults(func=cmd_say)

    from .skills.cli import add_subparser as _add_skills_subparser

    _add_skills_subparser(sub)

    from .mcp.cli import add_subparser as _add_mcp_subparser

    _add_mcp_subparser(sub)

    args = parser.parse_args()
    return args.func(args)


